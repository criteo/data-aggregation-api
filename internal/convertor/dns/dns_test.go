package dns_test

import (
	"testing"

	"github.com/google/go-cmp/cmp"
	"github.com/openconfig/ygot/ygot"

	dnsconvertors "github.com/criteo/data-aggregation-api/internal/convertor/dns"
	"github.com/criteo/data-aggregation-api/internal/model/cmdb/dns"
	"github.com/criteo/data-aggregation-api/internal/model/openconfig"
)

// dnsConfig is a DNS configuration as Netbox returns it, Device being an anonymous struct.
func dnsConfig(servers ...dns.Server) *dns.DNS {
	config := &dns.DNS{ServerList: servers}
	config.Device.Name = "tor01-01"
	return config
}

// serverAddresses returns the addresses of the servers, in order.
func serverAddresses(config *openconfig.System_Dns) []string {
	if config == nil {
		return nil
	}
	var out []string
	for _, s := range config.Server.Values() {
		out = append(out, *s.Address)
	}
	return out
}

func TestDNSToOpenconfig(t *testing.T) {
	tests := []struct {
		name string
		args *dns.DNS
		want []string
	}{
		{
			name: "servers sorted by address",
			args: dnsConfig(
				dns.Server{ServerAddress: "192.0.2.54"},
				dns.Server{ServerAddress: "2001:db8::53"},
				dns.Server{ServerAddress: "192.0.2.53"},
			),
			want: []string{"192.0.2.53", "192.0.2.54", "2001:db8::53"},
		},
		{
			name: "duplicate addresses",
			args: dnsConfig(
				dns.Server{Name: "dns1", ServerAddress: "192.0.2.53"},
				dns.Server{Name: "dns1-bis", ServerAddress: "192.0.2.53"},
			),
			want: []string{"192.0.2.53"},
		},
		{
			name: "no dns configuration",
			args: nil,
			want: nil,
		},
		{
			name: "no server",
			args: dnsConfig([]dns.Server{}...),
			want: nil,
		},
	}

	for _, test := range tests {
		out, err := dnsconvertors.DNSToOpenconfig(test.args)
		if err != nil {
			t.Errorf("unexpected error for '%s': %s", test.name, err)
			continue
		}
		if test.want == nil && out != nil {
			t.Errorf("unexpected configuration for '%s': %+v", test.name, out)
			continue
		}
		if diff := cmp.Diff(serverAddresses(out), test.want); diff != "" {
			t.Errorf("unexpected diff for '%s': %s\n", test.name, diff)
		}
	}
}

func TestDNSToOpenconfigJSON(t *testing.T) {
	config, err := dnsconvertors.DNSToOpenconfig(dnsConfig(
		dns.Server{ServerAddress: "192.0.2.54"},
		dns.Server{ServerAddress: "192.0.2.53"},
	))
	if err != nil {
		t.Fatal(err)
	}
	device := &openconfig.Device{System: &openconfig.System{Dns: config}}

	// ΛValidate is generated by ygot and checks the tree against the YANG schema; the Λ prefix keeps it
	// from colliding with YANG-derived names.
	if err := device.ΛValidate(); err != nil {
		t.Fatalf("generated DNS configuration is not valid OpenConfig: %s", err)
	}

	out, err := ygot.EmitJSON(
		device.System.Dns,
		&ygot.EmitJSONConfig{Format: ygot.RFC7951, SkipValidation: false, Indent: "  "},
	)
	if err != nil {
		t.Fatalf("generated DNS configuration cannot be emitted as JSON: %s", err)
	}

	want := `{
  "servers": {
    "server": [
      {
        "address": "192.0.2.53",
        "config": {
          "address": "192.0.2.53"
        }
      },
      {
        "address": "192.0.2.54",
        "config": {
          "address": "192.0.2.54"
        }
      }
    ]
  }
}`
	if diff := cmp.Diff(out, want); diff != "" {
		t.Errorf("unexpected JSON (-got +want):\n%s", diff)
	}
}
